def lookup_quick_answer(question: str) -> Optional[str]:
    """질문이 사전 정의된 정의형 질문에 매칭되면 즉시 답변 반환.

    Returns:
        정의된 답변 문자열 또는 None (매칭 안 되면 LLM 호출로 fallback)
    """
    if not question or not question.strip():
        return None
    for entry in QUICK_ANSWERS:
        for pat in entry["patterns"]:
            if re.search(pat, question, re.IGNORECASE):
                return entry["answer"]
    return None


